def _hit(tokens: List[str], key: str) -> bool:
    """Ключ совпал, если хоть одно слово вопроса начинается с него.

    Сравнение идёт и по корню: стеммер обрезает окончания («межевого» →
    «межев»), и ключ «межева» на таком слове уже не срабатывал.
    """
    for t in tokens:
        if t.startswith(key) or (len(t) >= 5 and key.startswith(t)):
            return True
        if len(t) >= 5 and len(key) >= 5 and t[:5] == key[:5]:
            return True
    return False


def match_topic(tokens: List[str]) -> Optional[Dict]:
    """Первая тема, под которую подходит вопрос (по порядку TOPICS)."""
    if not tokens:
        return None
    for topic in TOPICS:
        if "all" in topic and not all(_hit(tokens, k) for k in topic["all"]):
            continue
        if "any" in topic and not any(_hit(tokens, k) for k in topic["any"]):
            continue
        if "not" in topic and any(_hit(tokens, k) for k in topic["not"]):
            continue
        return topic
    return None
