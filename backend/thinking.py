def pick_scene(question: str, mode: str = "") -> str:
    """Выбирает сцену анимации по теме вопроса."""
    q = (question or "").lower()
    for scene, words in SCENE_RULES:
        for w in words:
            if w in q:
                return scene
    return "survey"


def extract_topic(question: str, limit: int = 2) -> str:
    """Выделяет короткую тему из вопроса — для заготовок подписей."""
    q = re.sub(r"[^\w\s-]", " ", (question or "").lower())
    words = [w for w in q.split() if len(w) > 3 and w not in _STOP]
    if not words:
        return "этот вопрос"
    return " ".join(words[:limit])


def _clean_line(raw: str) -> str:
    """Приводит строку модели к виду «фраза»."""
    s = raw.strip()
    s = re.sub(r"^[\-\*•\u2022\d]+[\.\)]?\s*", "", s)          # нумерация/маркеры
    s = s.strip(" \t\u00ab\u00bb\"'`«»")                          # кавычки
    s = re.sub(r"\s+", " ", s)
    s = s.rstrip(".…")
    return s.strip()


def _usable(text: str) -> bool:
    """Проверяет, что фраза годится для показа."""
    if not text:
        return False
    if not (8 <= len(text) <= 60):
        return False
    if re.search(r"\d", text):          # без цифр: цены, сроки, номера актов
        return False
    if re.search(r"http|www\.", text, re.IGNORECASE):
        return False
    if re.search(r"\bии\b|нейросет|openai|chatgpt|gpt|language model",
                 text, re.IGNORECASE):
        return False
    words = text.split()
    return 2 <= len(words) <= 8


CAPTION_PROMPT = """\
Ты — помощник кадастрового инженера. Придумай 4 короткие фразы (3–7 слов каждая), \
которые специалист мог бы произнести вслух, пока разбирается с вопросом клиента.

ТРЕБОВАНИЯ:
1. Фразы должны отражать ТЕМУ этого вопроса, а не быть общими.
2. Каждая фраза — самостоятельная, на одной строке, без нумерации и кавычек.
3. Никаких цифр, цен, дат, номеров документов и ссылок.
4. Не упоминай ИИ, нейросети, языковые модели и ассистентов — говори от лица специалиста.
5. Стиль: сухо, по-инженерному, с лёгкой иронией. Без канцелярита, без восклицательных знаков.
6. Не повторяй фразы из списка уже использованных.
7. Фразы должны быть разными между собой.

Уже использовано — не повторяй:
{used}

Вопрос клиента: {question}
"""


def fallback_captions(question: str, scene: str) -> List[str]:
    """Заготовленные подписи по сцене (модель недоступна или не ответила)."""
    topic = extract_topic(question)
    pool = FALLBACK_CAPTIONS.get(scene, FALLBACK_CAPTIONS["survey"])
    out: List[str] = []
    for tpl in pool:
        line = tpl.format(topic=topic)
        if line.lower() in {c.lower() for c in out}:
            continue
        out.append(line)
        if len(out) >= 3:
            break
    return out or [f"Разбираю вопрос про {topic}"]


class ThinkingCaptions:
    """Генератор подписей «размышления».

    Хранит недавние подписи, чтобы модель не выдавала одно и то же:
    «оригинальность» обеспечивается не только температурой, но и запретом
    повторов из истории.
    """

    def __init__(self, llm=None, max_used: int = 48):
        self._llm = llm
        self._used: deque = deque(maxlen=max_used)

    def set_llm(self, llm) -> None:
        self._llm = llm

    def _history(self) -> str:
        if not self._used:
            return "(пока пусто)"
        return "\n".join(f"- {c}" for c in list(self._used)[-24:])

    def remember(self, captions: List[str]) -> None:
        for c in captions:
            self._used.append(c)

    async def generate(
        self,
        question: str,
        mode: str = "",
        scene: Optional[str] = None,
    ) -> List[str]:
        """Возвращает 2–4 подписи. Никогда не бросает исключений."""
        scene = scene or pick_scene(question, mode)
        llm = self._llm
        if llm is not None:
            try:
                text = await asyncio.wait_for(
                    llm.chat_complete(
                        [{"role": "user", "content": CAPTION_PROMPT.format(
                            used=self._history(),
                            question=(question or "").strip(),
                        )}],
                        max_tokens=140,
                        temperature=0.95,
                    ),
                    timeout=CAPTION_TIMEOUT_S,
                )
                picked: List[str] = []
                for raw in (text or "").splitlines():
                    line = _clean_line(raw)
                    if not _usable(line):
                        continue
                    if line.lower() in {p.lower() for p in picked}:
                        continue
                    if line.lower() in {c.lower() for c in self._used}:
                        continue
                    picked.append(line)
                    if len(picked) >= 4:
                        break
                if picked:
                    self.remember(picked)
                    return picked
            except Exception:
                # модель недоступна — уходим на заготовки
                pass

        out = fallback_captions(question, scene)
        self.remember(out)
        return out
